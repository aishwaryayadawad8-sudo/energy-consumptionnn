"""
Quick Email Templates for SDG 7 Alert System
Pre-made templates for different alert types
"""


class EmailTemplates:
    """Quick email templates for different alert scenarios"""
    
    @staticmethod
    def urgent_alert(country, access, year):
        """🚨 Urgent Alert Template"""
        subject = f"🚨 URGENT: Immediate Action Required - Electricity Access Crisis in {country}"
        
        body = f"""
URGENT ALERT - IMMEDIATE ACTION REQUIRED

Country: {country}
Current Electricity Access: {access:.1f}%
Year: {year}
Status: CRITICAL

⚠️ SITUATION ANALYSIS:
Your country's electricity access rate of {access:.1f}% is critically below the SDG 7 target.
This requires immediate intervention to prevent further deterioration.

🚨 IMMEDIATE ACTIONS REQUIRED:
1. Declare energy emergency and mobilize resources
2. Fast-track renewable energy projects
3. Seek international aid and partnerships
4. Implement emergency rural electrification
5. Establish crisis management team

💰 FUNDING OPPORTUNITIES:
- World Bank Energy Access Fund
- UN Sustainable Energy for All Initiative
- Green Climate Fund
- Regional Development Banks

📞 CONTACT FOR SUPPORT:
SDG 7 Monitoring System
Email: support@sdg7alerts.org

This is an automated alert generated by ML predictions.
        """
        
        return subject, body
    
