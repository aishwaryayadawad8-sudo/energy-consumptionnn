    @staticmethod
    def get_template_by_type(template_type, country, access, year):
        """
        Get email template by type
        
        Args:
            template_type: 'urgent', 'reminder', 'congratulations', or 'status_update'
            country: Country name
            access: Electricity access percentage
            year: Year
            
        Returns:
            tuple: (subject, body)
        """
        templates = {
            'urgent': EmailTemplates.urgent_alert,
            'reminder': EmailTemplates.reminder,
            'congratulations': EmailTemplates.congratulations,
            'status_update': EmailTemplates.status_update
        }
        
        template_func = templates.get(template_type, EmailTemplates.status_update)
        return template_func(country, access, year)
    
    @staticmethod
    def get_all_template_types():
        """Get list of all available template types"""
        return [
            {'id': 'urgent', 'name': 'Urgent Alert', 'icon': '🚨', 'color': 'danger'},
            {'id': 'reminder', 'name': 'Reminder', 'icon': '📢', 'color': 'warning'},
            {'id': 'congratulations', 'name': 'Congratulations', 'icon': '🎉', 'color': 'success'},
            {'id': 'status_update', 'name': 'Status Update', 'icon': '📊', 'color': 'info'}
        ]
